IF OBJECT_ID ( '[CUDAPlugin].[DeleteAllMessages]', 'P' ) IS NOT NULL 
    DROP PROCEDURE [CUDAPlugin].[DeleteAllMessages];
GO

CREATE PROCEDURE [CUDAPlugin].[DeleteAllMessages]
AS
BEGIN
	SET NOCOUNT ON	
	SET TRANSACTION ISOLATION LEVEL SERIALIZABLE
	BEGIN TRY
		BEGIN TRANSACTION DELETEALLMESSAGES
		truncate table [CUDAPlugin].[Message]
		COMMIT TRANSACTION DELETEALLMESSAGES
	END TRY
	BEGIN CATCH
		ROLLBACK TRANSACTION DELETEALLMESSAGES
    SELECT
        ERROR_NUMBER() AS ErrorNumber
        ,ERROR_SEVERITY() AS ErrorSeverity
        ,ERROR_STATE() AS ErrorState
        ,ERROR_PROCEDURE() AS ErrorProcedure
        ,ERROR_LINE() AS ErrorLine
        ,ERROR_MESSAGE() AS ErrorMessage;
	END CATCH
END
GO