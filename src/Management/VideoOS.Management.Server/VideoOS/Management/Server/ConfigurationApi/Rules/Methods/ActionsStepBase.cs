using System;
using System.Collections.Generic;
using System.Linq;
using VideoOS.ConfigurationAPI;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Definitions;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain;
using VideoOS.Management.Server.ConfigurationApi.Rules.Proxies;
using VideoOS.Management.Server.Properties;

namespace VideoOS.Management.Server.ConfigurationApi.Rules.Methods;

public abstract class ActionsStepBase : StepBase
{
	protected readonly string ActionsPropertyKey;

	private readonly bool _isStartAction;

	private readonly string _actionPrefix;

	protected ActionsStepBase(bool isStartAction, IMIPActionProxy mipActionProxy, IMIPKindProxy mipKindProxy, IRecorderPluginProxy recorderPluginProxy, ISiteProxy siteProxy, IGeminiApplicationCoreProxy geminiApplicationCoreProxy)
		: base(mipActionProxy, mipKindProxy, recorderPluginProxy, siteProxy, geminiApplicationCoreProxy)
	{
		_isStartAction = isStartAction;
		if (isStartAction)
		{
			ActionsPropertyKey = "StartActions";
			_actionPrefix = "Start";
		}
		else
		{
			ActionsPropertyKey = "StopActions";
			_actionPrefix = "Stop";
		}
	}

	public override List<Property> GetCurrentProperties(IGeminiRequestContext requestContext, ConfigurationItem item, out string lastPropertyKey)
	{
		lastPropertyKey = "";
		List<Property> list = new List<Property>();
		if (item.TryGetPropertyValue(ActionsPropertyKey, out var result))
		{
			list.Add(GetActionsProperty(requestContext, ActionsPropertyKey, result, _isStartAction, item));
			foreach (IActionDefinition item2 in from at in StepBase.GetSelectedActionTypes(result)
				select _definitionsProvider.Get(requestContext, at))
			{
				AddParameterProperties(item, list, item2, out lastPropertyKey);
			}
			lastPropertyKey = (string.IsNullOrEmpty(lastPropertyKey) ? ActionsPropertyKey : lastPropertyKey);
		}
		return list;
	}

	public override List<Property> GetNextProperties(IGeminiRequestContext requestContext, ConfigurationItem item, string lastPropertyKey)
	{
		List<Property> list = new List<Property>();
		if (string.IsNullOrEmpty(lastPropertyKey))
		{
			list.Add(GetActionsProperty(requestContext, ActionsPropertyKey, "", _isStartAction, item));
			return list;
		}
		if (!item.TryGetPropertyValue(ActionsPropertyKey, out var result))
		{
			throw new ArgumentException("start actions property must have a value");
		}
		foreach (IActionDefinition item2 in from at in StepBase.GetSelectedActionTypes(result)
			select _definitionsProvider.Get(requestContext, at))
		{
			if (item2 != null)
			{
				AddMissingParameterProperties(item, list, item2, lastPropertyKey != ActionsPropertyKey);
			}
		}
		return list;
	}

	private void AddMissingParameterProperties(ConfigurationItem item, List<Property> result, IActionDefinition definition, bool skipExisting = false)
	{
		foreach (RuleParameterDefinition value in definition.Parameters.Values)
		{
			if (!value.IsVisible)
			{
				continue;
			}
			string text = ((!string.IsNullOrEmpty(value.PropertyName)) ? value.PropertyName : value.Name);
			string propertyName = _actionPrefix + "." + definition.ActionType + "." + text;
			if (skipExisting && item.IsPropertyValuePresent(propertyName))
			{
				continue;
			}
			if (result.Any((Property x) => x.Key == propertyName))
			{
				Property property = result.Single((Property x) => x.Key == propertyName);
				property.ValueTypeInfos = MergeValueTypeInfos(property.ValueTypeInfos, value);
				continue;
			}
			string propertyValue = "";
			if (value.AutoGenerated)
			{
				propertyValue = ((!(value.SpecialPropertyType == "Path") || value.AllowedItemTypes.Length == 0) ? value.DefaultValue : ConfigurationItemPath.CreateItemPath(value.AllowedItemTypes[0], value.DefaultValue).Text);
			}
			result.Add(ConfigurationItemActionHelper.GetProperty(value, propertyName, propertyValue));
		}
	}

	protected bool AreActionsComplete(ConfigurationItem item, IEnumerable<IActionDefinition> actionDefinitions)
	{
		return actionDefinitions.All((IActionDefinition x) => x == null || AreActionParametersRequiredAndPresent(item, x, x.ActionType));
	}

	private bool AreActionParametersRequiredAndPresent(ConfigurationItem item, IActionDefinition actionDefinition, string actionType)
	{
		return actionDefinition.Parameters.Values.All((RuleParameterDefinition def) => IsRequiredParameterPresent(item, def, actionType));
	}

	private bool IsRequiredParameterPresent(ConfigurationItem item, RuleParameterDefinition parameterDefinition, string actionType)
	{
		if (parameterDefinition.IsVisible)
		{
			string text = ((!string.IsNullOrEmpty(parameterDefinition.PropertyName)) ? parameterDefinition.PropertyName : parameterDefinition.Name);
			string propertyName = _actionPrefix + "." + actionType + "." + text;
			if ((!parameterDefinition.EmptyAllowed && !parameterDefinition.AutoGenerated) || !string.IsNullOrEmpty(parameterDefinition.PairedParameter))
			{
				if (!item.IsPropertyValuePresent(propertyName))
				{
					return false;
				}
			}
			else if (!item.IsPropertyPresent(propertyName))
			{
				return false;
			}
		}
		return true;
	}

	protected static ValueTypeInfo[] MergeValueTypeInfos(ValueTypeInfo[] valueTypeInfos, RuleParameterDefinition parameter)
	{
		ValueTypeInfo[] valueTypeInfos2 = ConfigurationItemActionHelper.GetValueTypeInfos(parameter);
		List<ValueTypeInfo> list = valueTypeInfos.ToList();
		list.AddRange(valueTypeInfos2);
		return list.ToArray();
	}

	protected Property GetActionsProperty(IGeminiRequestContext requestContext, string actionsPropertyKey, string actionsPropertyValue, bool isStart, ConfigurationItem item)
	{
		IDictionary<string, string> actionsForDisplay = _definitionsProvider.GetActionsForDisplay(requestContext, isStart, GetRuleType(item, isStart));
		return GeneralPropertyDefinitions.GetListProperty(actionsPropertyValue, actionsPropertyKey, isStart ? ConfigurationApiResources.PropertyRuleStartActions : ConfigurationApiResources.PropertyRuleStopActions, isStart ? "PropertyRuleStartActions" : "PropertyRuleStopActions", isSettable: true, actionsForDisplay);
	}

	private void AddParameterProperties(ConfigurationItem item, List<Property> result, IActionDefinition definition, out string lastPropertyKey)
	{
		lastPropertyKey = "";
		if (definition == null)
		{
			return;
		}
		foreach (RuleParameterDefinition value in definition.Parameters.Values)
		{
			string propertyName = GetPropertyName(definition.ActionType.ToString(), value);
			if (!item.TryGetPropertyValue(propertyName, out var result2))
			{
				continue;
			}
			if (result.Any((Property x) => x.Key == propertyName))
			{
				Property property = result.Single((Property x) => x.Key == propertyName);
				property.ValueTypeInfos = MergeValueTypeInfos(property.ValueTypeInfos, value);
			}
			else
			{
				result.Add(ConfigurationItemActionHelper.GetProperty(value, propertyName, result2));
			}
			lastPropertyKey = propertyName;
		}
	}

	private string GetPropertyName(string actionType, RuleParameterDefinition definition)
	{
		string text = ((!string.IsNullOrEmpty(definition.PropertyName)) ? definition.PropertyName : definition.Name);
		return _actionPrefix + "." + actionType + "." + text;
	}

	private static TriggerType GetRuleType(ConfigurationItem item, bool isStart)
	{
		string propertyName = (isStart ? "StartRuleType" : "StopRuleType");
		if (item.TryGetPropertyValue(propertyName, out var result) && Enum.TryParse<TriggerType>(result, out var result2))
		{
			return result2;
		}
		return TriggerType.None;
	}
}
