using System;
using System.Collections.Generic;
using System.Linq;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Validation;
using VideoOS.Management.Server.Properties;

namespace VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Definitions;

public class StartPatrollingActionDefinition : IActionDefinition
{
	public string ActionType => VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain.ActionType.StartPatrolling.ToString();

	public IDictionary<string, RuleParameterDefinition> Parameters => CreateParameters();

	public string CounteractionActionType => VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain.ActionType.StopPatrolling.ToString();

	public string DisplayName => ConfigurationApiResources.RuleActionStartPatrollingProfile;

	public ActionPosition Position => ActionPosition.Start;

	public IEnumerable<string> RequiredFeatures => new string[0];

	public IEnumerable<TriggerType> ValidForTriggerTypes => new TriggerType[3]
	{
		TriggerType.Event,
		TriggerType.TimeInterval,
		TriggerType.Timer
	};

	private static IDictionary<string, RuleParameterDefinition> CreateParameters()
	{
		return new RuleParameterDefinition[4]
		{
			new RuleParameterDefinition
			{
				Name = "State",
				DefaultValue = "On",
				AutoGenerated = true,
				ValueType = typeof(string),
				IsVisible = false
			},
			new RuleParameterDefinition
			{
				Name = "DeviceId",
				ValueType = typeof(Guid),
				EmptyAllowed = false,
				SpecialPropertyType = "Path",
				AllowedItemTypes = new string[1] { "Camera" },
				ValidatorType = typeof(DeviceParameterValueValidator)
			},
			new RuleParameterDefinition
			{
				Name = "PatrollingSchemaId",
				ValueType = typeof(Guid),
				EmptyAllowed = false,
				SpecialPropertyType = "Path",
				AllowedItemTypes = new string[1] { "PatrollingProfile" },
				ValidatorType = typeof(PatrollingProfileParameterValueValidator)
			},
			new RuleParameterDefinition
			{
				Name = "Priority",
				ValueType = typeof(int),
				MinValue = 1,
				MaxValue = 32000
			}
		}.ToDictionary((RuleParameterDefinition s) => s.Name);
	}
}
