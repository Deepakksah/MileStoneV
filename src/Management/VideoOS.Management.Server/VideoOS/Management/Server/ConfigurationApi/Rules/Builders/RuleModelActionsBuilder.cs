using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using VideoOS.ConfigurationAPI;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Definitions;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain;
using VideoOS.Management.Server.ConfigurationApi.Rules.Proxies;

namespace VideoOS.Management.Server.ConfigurationApi.Rules.Builders;

public class RuleModelActionsBuilder : RuleModelBuilderBase, IRuleModelActionsBuilder
{
	private ActionDefinitionsProvider _actionDefinitionsProvider;

	public RuleModelActionsBuilder(IMIPActionProxy mipActionProxy, IMIPKindProxy mipKindProxy, IRecorderPluginProxy recorderPluginProxy, ISiteProxy siteProxy, IGeminiApplicationCoreProxy geminiApplicationCoreProxy)
	{
		_actionDefinitionsProvider = new ActionDefinitionsProvider(mipActionProxy, mipKindProxy, recorderPluginProxy, siteProxy, geminiApplicationCoreProxy);
	}

	public IEnumerable<ActionModel> Build(IGeminiRequestContext requestContext, ConfigurationItem item, string prefix, bool isStartAction)
	{
		if (!item.TryGetPropertyValue(isStartAction ? "StartActions" : "StopActions", out var result) || string.IsNullOrEmpty(result))
		{
			return new List<ActionModel>();
		}
		return (from s in result.Split(';')
			select s.Trim() into type
			select CreateActionModel(requestContext, type, item, prefix)).ToArray();
	}

	private ActionModel CreateActionModel(IGeminiRequestContext requestContext, string type, ConfigurationItem item, string prefix)
	{
		IActionDefinition actionDefinition = _actionDefinitionsProvider.Get(requestContext, type);
		IDictionary<string, RuleParameterDefinition> dictionary = actionDefinition?.Parameters;
		return new ActionModel
		{
			ActionType = type,
			Parameters = AddCopyCounterActionParameters(actionDefinition, AddDefaultActionParameters(dictionary, ReadActionParameters(item, prefix, type, dictionary)), item)
		};
	}

	private static IDictionary<string, RuleParameter> AddCopyCounterActionParameters(IActionDefinition actionDefinition, RuleParameter[] existingAndDefaultParameters, ConfigurationItem item)
	{
		List<RuleParameter> list = new List<RuleParameter>();
		if (actionDefinition != null)
		{
			IEnumerable<RuleParameterDefinition> enumerable = actionDefinition.Parameters?.Values.Where((RuleParameterDefinition x) => !x.IsVisible && !x.AutoGenerated && !existingAndDefaultParameters.Any((RuleParameter t) => t.Name == x.Name));
			List<string> list2 = new List<string>();
			if (enumerable != null)
			{
				foreach (RuleParameterDefinition item2 in enumerable)
				{
					string copyPropertyName = GetCopyPropertyName(actionDefinition, item2);
					Property property = item.Properties.FirstOrDefault((Property x) => x.Key == copyPropertyName);
					if (property != null && !list2.Contains(property.Key))
					{
						list.AddRange(GetRuleParameters(property, item2, enumerable));
						list2.Add(property.Key);
					}
				}
			}
		}
		return existingAndDefaultParameters.Concat(list).ToDictionary((RuleParameter s) => s.Name);
	}

	private static string GetCopyPropertyName(IActionDefinition actionDefinition, RuleParameterDefinition copyDefinition)
	{
		string counteractionActionType = actionDefinition.CounteractionActionType;
		if (counteractionActionType == ActionType.None.ToString())
		{
			return "";
		}
		string arg = ((actionDefinition.Position == ActionPosition.Start) ? "Stop" : "Start");
		string arg2 = (string.IsNullOrEmpty(copyDefinition.PropertyName) ? copyDefinition.Name : copyDefinition.PropertyName);
		return string.Format(CultureInfo.InvariantCulture, "{0}.{1}.{2}", arg, counteractionActionType, arg2);
	}

	private static RuleParameter[] AddDefaultActionParameters(IDictionary<string, RuleParameterDefinition> parameterDefinitions, IDictionary<string, RuleParameter> existingParameters)
	{
		RuleParameter[] first = ((parameterDefinitions != null) ? (from s in parameterDefinitions.Values
			where s.AutoGenerated && !existingParameters.ContainsKey(s.Name)
			select new RuleParameter
			{
				Name = s.Name,
				Value = s.DefaultValue,
				XmlName = s.XmlName,
				ParameterToAppend = s.ParameterToAppend,
				ExcludeFromDatabase = s.ExcludeFromDatabase
			}).ToArray() : new RuleParameter[0]);
		return first.Concat(existingParameters.Values).ToArray();
	}

	private static IDictionary<string, RuleParameter> ReadActionParameters(ConfigurationItem item, string prefix, string type, IDictionary<string, RuleParameterDefinition> definitions)
	{
		string propertyPrefix = prefix + "." + type + ".";
		IEnumerable<Property> enumerable = item.Properties.Where((Property s) => s.Key.StartsWith(propertyPrefix, StringComparison.Ordinal));
		List<RuleParameter> list = new List<RuleParameter>();
		foreach (Property item2 in enumerable)
		{
			RuleParameterDefinition value = null;
			if (definitions != null)
			{
				definitions.TryGetValue(item2.Key.Split('.')[2], out value);
			}
			list.AddRange(from s in GetRuleParameters(item2, value, definitions?.Values)
				where IsAllowedParameter(s, definitions)
				select s);
		}
		return list.ToDictionary((RuleParameter s) => s.Name);
	}

	private static bool IsAllowedParameter(RuleParameter parameter, IDictionary<string, RuleParameterDefinition> definitions)
	{
		if (definitions == null)
		{
			return true;
		}
		if (!definitions.TryGetValue(parameter.Name, out var value))
		{
			return false;
		}
		return value.IsVisible;
	}

	private static RuleParameter[] GetRuleParameters(Property property, RuleParameterDefinition definition, IEnumerable<RuleParameterDefinition> definitions)
	{
		string name = property.Key.Split('.')[2];
		List<RuleParameter> list = new List<RuleParameter>(2) { CreateRuleParameter(name, from s in RuleModelBuilderBase.ExtractPaths(property.Value)
			where !RuleModelBuilderBase.IsGroup(s.ItemType)
			select s, definition) };
		if (!string.IsNullOrEmpty(definition.PairedParameter) && string.IsNullOrEmpty(definition.PropertyName) && definitions != null)
		{
			RuleParameterDefinition ruleParameterDefinition = definitions.FirstOrDefault((RuleParameterDefinition d) => d.Name == definition.PairedParameter);
			if (ruleParameterDefinition != null)
			{
				list.Add(CreateRuleParameter(definition.PairedParameter, from s in RuleModelBuilderBase.ExtractPaths(property.Value)
					where RuleModelBuilderBase.IsGroup(s.ItemType)
					select s, ruleParameterDefinition));
			}
		}
		return list.ToArray();
	}

	private static RuleParameter CreateRuleParameter(string name, IEnumerable<ConfigurationItemPath> paths, RuleParameterDefinition definition)
	{
		RuleParameter ruleParameter = new RuleParameter
		{
			Name = name,
			Values = paths.Select((ConfigurationItemPath path) => path.Id).ToArray()
		};
		if (definition != null)
		{
			ruleParameter.ParameterToAppend = definition.ParameterToAppend;
			ruleParameter.ExcludeFromDatabase = definition.ExcludeFromDatabase;
			ruleParameter.XmlName = definition.XmlName;
		}
		if (ruleParameter.Values == null || ruleParameter.Value == null)
		{
			ruleParameter.Value = ((definition != null && definition.DefaultValue != null) ? definition.DefaultValue : "");
		}
		return ruleParameter;
	}
}
