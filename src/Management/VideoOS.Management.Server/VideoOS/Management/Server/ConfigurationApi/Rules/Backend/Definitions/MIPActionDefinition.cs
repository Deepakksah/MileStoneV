using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain;
using VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Validation;

namespace VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Definitions;

public class MIPActionDefinition : IActionDefinition
{
	private readonly string _id;

	private readonly string _name;

	private readonly string[] _itemTypes;

	private readonly string[] _groupItemTypes;

	private readonly Guid[] _mipKinds;

	private readonly bool _isAccessControl;

	public string ActionType => string.Format(CultureInfo.InvariantCulture, VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain.ActionType.MIPAction.ToString() + ":" + _id);

	public IDictionary<string, RuleParameterDefinition> Parameters => CreateParameters();

	public string CounteractionActionType => VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Domain.ActionType.None.ToString();

	public string DisplayName { get; }

	public ActionPosition Position => ActionPosition.None;

	public IEnumerable<string> RequiredFeatures => new string[0];

	public IEnumerable<TriggerType> ValidForTriggerTypes => new TriggerType[3]
	{
		TriggerType.Event,
		TriggerType.RecurringTime,
		TriggerType.TimeInterval
	};

	public MIPActionDefinition(string id, string name, string displayName, string[] itemTypes, string[] groupItemTypes, Guid[] mipKinds, bool isAccessControl)
	{
		_id = id;
		_name = name;
		DisplayName = displayName;
		_itemTypes = itemTypes;
		_groupItemTypes = groupItemTypes;
		_mipKinds = mipKinds;
		_isAccessControl = isAccessControl;
	}

	private IDictionary<string, RuleParameterDefinition> CreateParameters()
	{
		return new RuleParameterDefinition[5]
		{
			new RuleParameterDefinition
			{
				Name = "Delay",
				DefaultValue = "0",
				AutoGenerated = true,
				ValueType = typeof(int),
				MinValue = -2147482800,
				MaxValue = 2147482800
			},
			new RuleParameterDefinition
			{
				Name = "MipId",
				DefaultValue = _id,
				AutoGenerated = true,
				ValueType = typeof(Guid),
				IsVisible = false
			},
			new RuleParameterDefinition
			{
				Name = "MipName",
				DefaultValue = _name,
				AutoGenerated = true,
				ValueType = typeof(string),
				IsVisible = false
			},
			new RuleParameterDefinition
			{
				Name = "Items",
				PairedParameter = "ItemGroups",
				ValueType = typeof(Guid[]),
				EmptyAllowed = true,
				SpecialPropertyType = "PathList",
				AllowedItemTypes = _itemTypes,
				AllowedMIPKinds = _mipKinds,
				ValidatorType = (_isAccessControl ? typeof(AccessControlEventParameterValueValidator) : (_mipKinds.Any() ? typeof(PluginItemParameterValueValidator) : typeof(DeviceParameterValueValidator)))
			},
			new RuleParameterDefinition
			{
				Name = "ItemGroups",
				PropertyName = "Items",
				PairedParameter = "Items",
				ValueType = typeof(Guid[]),
				EmptyAllowed = true,
				SpecialPropertyType = "PathList",
				AllowedItemTypes = _groupItemTypes,
				AllowedMIPKinds = _mipKinds,
				ValidatorType = (_isAccessControl ? typeof(AccessControlGroupEventParameterValueValidator) : (_mipKinds.Any() ? typeof(PluginGroupItemParameterValueValidator) : typeof(DeviceGroupParameterValueValidator)))
			}
		}.ToDictionary((RuleParameterDefinition s) => s.Name);
	}
}
