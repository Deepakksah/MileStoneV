IF EXISTS(SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[delete_states_by_datacollector]') AND type = 'P')
DROP PROCEDURE [delete_states_by_datacollector]
GO

CREATE PROCEDURE [delete_states_by_datacollector]
	@dataCollectorId INT,
	@paths tvp_StringTableNvarchar READONLY
AS
BEGIN
	SET NOCOUNT ON
 
	-- Initialize the ProcedureName for error messages.
	DECLARE @procedureName SYSNAME
	SELECT  @procedureName = @@SERVERNAME + '.' + db_name() + '..' + object_name(@@PROCID)
	DECLARE @ErrorArgs NVARCHAR(500)

	BEGIN TRY
		BEGIN TRAN

		-- Deleted states 
		DELETE FROM [MonitorStates] 
		WHERE [data_collector_id] = @dataCollectorId AND [counter_path] NOT IN (SELECT ID FROM @paths)

		COMMIT TRAN
	END TRY
	BEGIN CATCH 
		IF @@TRANCOUNT > 0
		BEGIN
			ROLLBACK TRANSACTION
		END;
		DECLARE @shouldReThrowError BIT = dbo.[ShouldReThrowError](ERROR_NUMBER(), ERROR_SEVERITY())
		IF(@shouldReThrowError = 1)
			THROW;
		SET @ErrorArgs = dbo.[FormatErrorMessage](ERROR_NUMBER(), ERROR_SEVERITY(), ERROR_STATE(), ERROR_PROCEDURE(), ERROR_LINE(), ERROR_MESSAGE())
		;THROW 60000, @ErrorArgs, 1;
	END CATCH;
END
GO