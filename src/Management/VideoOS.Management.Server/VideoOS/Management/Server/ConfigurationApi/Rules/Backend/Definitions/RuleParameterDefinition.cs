using System;
using System.Collections.Generic;

namespace VideoOS.Management.Server.ConfigurationApi.Rules.Backend.Definitions;

public class RuleParameterDefinition
{
	public string Name { get; set; }

	public string PropertyName { get; set; }

	public bool AutoGenerated { get; set; }

	public string DefaultValue { get; set; }

	public Type ValueType { get; set; } = typeof(string);

	public bool EmptyAllowed { get; set; }

	public bool IsVisible { get; set; } = true;

	public IComparable MinValue { get; set; }

	public IComparable MaxValue { get; set; }

	public string[] AllowedItemTypes { get; set; } = new string[0];

	public IDictionary<string, string> AllowedKeyValuePairs { get; }

	public Guid[] AllowedMIPKinds { get; set; } = new Guid[0];

	public bool IsGroup { get; set; }

	public Type ValidatorType { get; set; }

	public string SpecialPropertyType { get; set; }

	public string PairedParameter { get; set; }

	public string ParameterToAppend { get; set; }

	public bool ExcludeFromDatabase { get; set; }

	public string XmlName { get; set; }

	public string ToolTipTranslationId { get; set; }

	public RuleParameterDefinition()
	{
		AllowedKeyValuePairs = new Dictionary<string, string>();
	}

	public RuleParameterDefinition(IDictionary<string, string> allowedKeyValuePairs)
	{
		AllowedKeyValuePairs = allowedKeyValuePairs;
	}
}
