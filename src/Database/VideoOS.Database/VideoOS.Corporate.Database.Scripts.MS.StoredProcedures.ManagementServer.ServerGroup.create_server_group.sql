IF EXISTS(SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[create_server_group]') AND type = 'P')
DROP PROCEDURE [create_server_group]
GO

CREATE PROCEDURE [create_server_group]
	@IDServerGroup [GuidType],
	@Name [NameType],
	@Description NVARCHAR(1024),
	@IDParentGroup [GuidType],
	@StructureType VARCHAR(64),
	@user_sid [SIDType],
	@custom_properties XML = NULL
AS
BEGIN
	SET NOCOUNT ON
 
	-- Initialize the ProcedureName for error messages.
	DECLARE @procedureName SYSNAME
	SELECT  @procedureName = @@SERVERNAME + '.' + db_name() + '..' + object_name(@@PROCID)
	DECLARE @ErrorArgs NVARCHAR(500)

	BEGIN TRY
		BEGIN TRANSACTION

		EXEC [create_server_group_transaction]
			@IDServerGroup, @Name, @Description, @IDParentGroup, @StructureType, @user_sid, @custom_properties

		COMMIT TRANSACTION
	END TRY
	BEGIN CATCH 
		IF @@TRANCOUNT > 0
		BEGIN
			ROLLBACK TRANSACTION
		END;
		DECLARE @shouldReThrowError BIT = dbo.[ShouldReThrowError](ERROR_NUMBER(), ERROR_SEVERITY())
		IF(@shouldReThrowError = 1)
			THROW;
		SET @ErrorArgs = dbo.[FormatErrorMessage](ERROR_NUMBER(), ERROR_SEVERITY(), ERROR_STATE(), ERROR_PROCEDURE(), ERROR_LINE(), ERROR_MESSAGE())
		;THROW 60000, @ErrorArgs, 1;
	END CATCH;
END
GO